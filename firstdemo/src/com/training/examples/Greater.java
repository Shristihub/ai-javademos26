package com.training.examples;

public class Greater {

	public static void main(String[] args) {
		// create three nums
		int x = 10;
		int y = 10;
		int z = 30;

		if (x > y && x > z) {
			System.out.println("X is greater");
		} else if (y > z) {
			System.out.println("y is greater");
		} else {
			System.out.println("Z is greater");
		}

	}

}

